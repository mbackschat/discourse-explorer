"""Discourse REST API client used by the live-`init` pipeline (Sit 13).

The seeder talks to a Discourse instance over HTTP using the standard admin
API surface: `Api-Key` + `Api-Username` headers on every request. This file
deliberately mirrors `discourse_explorer/scraper.py`'s conventions — same
header names, same `requests.Session`-based plumbing, same retry behaviour
on 429 / 5xx — so a future maintainer recognising one client recognises the
other.

Scope: just the create-side of the API. Sit 14 will use these to push the
generators' output into the live forum (`pipeline.init`). Read paths stay
in the parent project's `scraper.py` — there's no need to duplicate them
here.

Discourse-specific quirks worth knowing:

* **Topic creation goes through `POST /posts.json`** — Discourse only has a
  posts endpoint; passing a `title` + `category` (no `topic_id`) is what
  causes a topic to be created (the response carries the new `topic_id`
  alongside the OP post `id`). This matches the
  `docs/discourse/DISCOURSE_JSON_TERMINOLOGY.md` model: a topic is just the
  metadata wrapper around its OP.
* **Backdating via `created_at`** is honoured only for requests
  authenticated as a master-key user — the admin key generated by
  Sit 13's `make api-key` (rails runner inside the bitnami container) has
  this. ISO 8601 strings (e.g. `"2025-04-26T10:30:00Z"`) are accepted.
* **Author impersonation** is per-request: the `Api-Username` header on a
  given call decides who the post / topic appears to be authored by.
  `_request(..., as_username=...)` swaps just that one header for the call
  without persisting on the session.
* **Tag pre-creation** is unnecessary in current Discourse versions — tags
  are auto-created when first associated with a topic, and the explicit
  tag-management endpoint is mostly relevant for renaming / grouping. The
  `create_tag` method here is a documented no-op so the seeder pipeline
  can call it idempotently for parity with categories / users.

Errors raise `DiscourseAPIError` with URL + status + body for diagnostics —
the alternative (raw `requests.HTTPError`) hides the response payload, which
is where Discourse's actual validation messages live.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any, Optional

import requests
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry


# ---------------------------------------------------------------------------
# Retry config (mirrors discourse_explorer/scraper.py conventions)
# ---------------------------------------------------------------------------

# 3 retries with exponential backoff (factor 0.5 → waits 0.5s, 1s, 2s) on
# 429 + 5xx. Kept identical to the parent scraper's behaviour so a maintainer
# tuning one knows the other follows suit. POST is not in urllib3's default
# `allowed_methods`, so we list every verb we use explicitly.
_RETRY_TOTAL = 3
_RETRY_BACKOFF = 0.5
_RETRY_STATUS_FORCELIST = (429, 500, 502, 503, 504)
_RETRY_METHODS = frozenset({"GET", "POST", "PUT", "DELETE"})

# Sit 14.1: when urllib3's retry budget exhausts on 429, we recover at the
# `_request` layer with a fixed sleep + retry, up to N additional rounds. The
# 30-second window roughly matches Discourse's Rack::Attack burst-window
# default; bursts that fill the window in <30s recover cleanly. Keep
# `MAX_RETRIES` modest — repeated 429s past this point indicate a config
# issue (e.g. an untuned Discourse setting or a per-IP daily cap) rather
# than a transient burst.
_RATE_LIMIT_BACKOFF = 30.0
_RATE_LIMIT_MAX_RETRIES = 3


# ---------------------------------------------------------------------------
# Errors
# ---------------------------------------------------------------------------


class DiscourseAPIError(RuntimeError):
    """Raised when a Discourse API call returns a non-2xx response.

    Carries the request URL, the HTTP status code, and the raw response body.
    Discourse's validation errors live in the body (`{"errors": [...]}`), so
    surfacing it verbatim is what makes diagnostics actually useful.
    """

    def __init__(self, *, url: str, status: int, body: str):
        self.url = url
        self.status = status
        self.body = body
        super().__init__(
            f"Discourse API call failed: {status} on {url}\n"
            f"  body: {body[:500]}{'...' if len(body) > 500 else ''}"
        )


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _to_iso(ts: datetime) -> str:
    """Render a `datetime` as an ISO 8601 string Discourse accepts.

    Naive datetimes are assumed to be UTC; aware datetimes are converted to
    UTC and emitted with the trailing `Z` Discourse's API examples use. This
    is the single source of truth for `created_at` formatting — both
    `create_topic` and `create_post` call it so a future format change lands
    in one place.
    """
    if ts.tzinfo is None:
        ts = ts.replace(tzinfo=timezone.utc)
    else:
        ts = ts.astimezone(timezone.utc)
    # `isoformat()` emits `+00:00`; Discourse + every other tool accepts `Z`.
    return ts.replace(tzinfo=None).isoformat(timespec="seconds") + "Z"


